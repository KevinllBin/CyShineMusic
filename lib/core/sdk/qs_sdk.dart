typedef QsJsonRequester =
    Future<dynamic> Function(
      String url, {
      required String method,
      required Map<String, String> headers,
      String? body,
    });

// Public catalogue and lyrics. Playback is handled by imported sources.
final qishuiSdk = QsSdk();

class QsEmptyResponseException implements Exception {
  const QsEmptyResponseException();
  @override
  String toString() => '汽水音乐暂时没有返回数据，请稍后重试';
}

class QsSdk {
  QsSdk({QsJsonRequester? requester}) : _requester = requester ?? _fetch;

  final QsJsonRequester _requester;
  Future<Map>? _pendingDiscover;

  static const _commonParams = {
    'aid': '386088',
    'app_name': 'luna_pc',
    'region': 'cn',
    'geo_region': 'cn',
    'os_region': 'cn',
    'version_name': '3.7.0',
    'version_code': '3.7.0',
    'channel': 'official',
    'build_mode': 'master',
    'ac': 'wifi',
    'tz_name': 'Asia/Shanghai',
    'device_platform': 'windows',
    'device_type': 'Windows',
    'os_version': 'Windows 10 Pro',
  };

  Future<Map> request(
    String path, {
    Map<String, String> query = const {},
    Map<String, Object?>? body,
  }) async {
    final payload = body == null ? null : jsonEncode(body);
    // Keep `search_id=` rather than the bare `search_id` generated by
    // queryParameters for empty strings; the search gateway rejects bare keys.
    final encodedQuery = {..._commonParams, ...query}.entries
        .map(
          (entry) =>
              '${Uri.encodeQueryComponent(entry.key)}=${Uri.encodeQueryComponent(entry.value)}',
        )
        .join('&');
    final value = await _requester(
      Uri.https('api.qishui.com', path).replace(query: encodedQuery).toString(),
      method: payload == null ? 'GET' : 'POST',
      headers: {
        'User-Agent': 'LunaPC/3.7.0(official)',
        'Accept': 'application/json',
        'x-luna-is-local-user': '0',
        if (payload != null) ...{
          'Content-Type': 'application/json; charset=utf-8',
          'x-ss-stub': CryptoUtil.md5Hex(payload).toUpperCase(),
        },
      },
      body: payload,
    );
    if (value == null || (value is String && value.trim().isEmpty)) {
      throw const QsEmptyResponseException();
    }
    final decoded = value is String ? jsonDecode(value) : value;
    if (decoded is! Map) throw Exception('汽水音乐返回了无效数据');
    final code = _int(decoded['status_code']) ?? 0;
    if (code != 0) throw Exception('汽水音乐请求失败（$code）');
    return decoded;
  }

  static Future<dynamic> _fetch(
    String url, {
    required String method,
    required Map<String, String> headers,
    String? body,
  }) async => (await SdkHttp.fetch<dynamic>(
    url,
    method: method,
    headers: headers,
    body: body,
  )).body;

  // Coalesce concurrent playlist/board loads without keeping stale recommendations.
  Future<Map> _discover() => _pendingDiscover ??= _loadDiscover();

  Future<Map> _loadDiscover() async {
    try {
      // The newer listening-mode layout omits the leaderboard blocks.
      final data = await request('/luna/pc/discover', body: const {});
      if (data['blocks'] is! List) throw Exception('汽水音乐发现页加载失败');
      return data;
    } finally {
      _pendingDiscover = null;
    }
  }

  Future<List<PlaylistSummary>> featured({int page = 1, int limit = 20}) async {
    // This endpoint supplies a finite homepage selection, not numbered pages.
    if (page > 1 || limit <= 0) return const [];
    final home = await _discover();
    final seen = <String>{};
    return [
      for (final block in (home['blocks'] as List).whereType<Map>())
        if (block['type'] == 'discover_feed_playlist')
          for (final inner in _maps(block['inner_block']))
            for (final resource in _maps(inner['resources']))
              if (_map(resource['entity'])['playlist'] case final Map item)
                if (_text(item['id']) case final String id)
                  if (seen.add(id))
                    PlaylistSummary(
                      id: id,
                      name: _text(item['title']) ?? '汽水歌单',
                      source: MusicSource.qs,
                      coverUrl: imageUrl(item['url_cover']),
                      creator: _text(_map(item['owner'])['nickname']),
                      description: _text(item['desc']),
                      trackCount: _int(item['count_tracks']),
                    ),
    ].take(limit).toList(growable: false);
  }

  Future<List<LeaderboardSummary>> boards() async {
    final home = await _discover();
    final seen = <String>{};
    return [
      for (final block in (home['blocks'] as List).whereType<Map>())
        if (block['type'] == 'discover_top_song_list')
          for (final inner in _maps(block['inner_block']))
            if (inner['type'] == 'discover_track_top_list')
              if (_text(inner['inner_block_id']) case final String id)
                if (seen.add(id)) _board(id, inner),
    ];
  }

  static LeaderboardSummary _board(String id, Map inner) {
    final tracks = _rankedTracks(inner['resources']);
    return LeaderboardSummary(
      id: 'qs__$id',
      boardId: id,
      name: _text(inner['title']) ?? '汽水排行榜',
      source: MusicSource.qs,
      coverUrl: tracks.firstOrNull?.meta.picUrl,
      updateFrequency: _text(inner['desc']),
      previewTracks: tracks.take(3).toList(growable: false),
    );
  }

  Future<PlaylistInfo> leaderboard(String id, {int? maxTracks}) async {
    final nativeId = id.startsWith('chart:') ? id.substring(6) : id;
    final data = await request('/luna/pc/charts/$nativeId');
    final chart = data['chart'];
    if (chart is! Map || chart['track_ranks'] is! List) {
      throw Exception('汽水音乐榜单加载失败');
    }
    final tracks = [
      for (final rank in _maps(chart['track_ranks']))
        if (parseTrack(_map(rank['track'])) case final MusicInfo music) music,
    ];
    return PlaylistInfo(
      // Preserve the collection type when a saved chart is updated as a playlist.
      id: 'chart:$nativeId',
      name: _text(chart['title']) ?? '汽水排行榜',
      source: MusicSource.qs,
      tracks: tracks.take(_limit(maxTracks)).toList(growable: false),
      coverUrl: imageUrl(chart['url_cover']) ?? tracks.firstOrNull?.meta.picUrl,
      creator: '汽水音乐',
      description: _text(_map(chart['style'])['desc']),
      trackCount: tracks.length,
    );
  }

  Future<PlaylistInfo> playlist(String id, {int? maxTracks}) async {
    final limit = _limit(maxTracks);
    final tracks = <MusicInfo>[];
    final seen = <String>{};
    final cursors = <String>{};
    var cursor = '';
    var session = '';
    var exhausted = false;
    Map? info;
    while (tracks.length < limit && cursors.add(cursor)) {
      final remaining = limit - tracks.length;
      final data = await request(
        '/luna/pc/playlist/detail',
        query: {
          'playlist_id': id,
          'cursor': cursor,
          'count': '${remaining.clamp(1, 100)}',
          'session_id': session,
        },
      );
      if (data['playlist'] is! Map || data['media_resources'] is! List) {
        throw Exception('汽水音乐歌单加载失败');
      }
      info ??= data['playlist'] as Map;
      for (final resource in _maps(data['media_resources'])) {
        final entity = _map(resource['entity']);
        final raw = _map(entity['track_wrapper'])['track'] ?? entity['track'];
        final music = parseTrack(_map(raw));
        if (music != null && seen.add(music.id)) tracks.add(music);
      }
      final nextCursor = _text(data['next_cursor']);
      if (data['has_more'] != true) {
        exhausted = true;
        break;
      }
      if (nextCursor == null || cursors.contains(nextCursor)) {
        throw Exception('汽水音乐歌单分页异常，请稍后重试');
      }
      cursor = nextCursor;
      session = _text(data['session_id']) ?? session;
    }
    final playlist = info!;
    return PlaylistInfo(
      id: id,
      name: _text(playlist['title']) ?? '汽水歌单',
      source: MusicSource.qs,
      tracks: tracks.take(limit).toList(growable: false),
      coverUrl: imageUrl(playlist['url_cover']),
      creator: _text(_map(playlist['owner'])['nickname']),
      description: _text(playlist['desc']),
      // Removed/unavailable resources can make the advertised count too large.
      trackCount: exhausted ? tracks.length : _int(playlist['count_tracks']),
    );
  }

  Future<LyricInfo> getLyric(MusicInfo music) async {
    final data = await request(
      '/luna/h5/track_v2',
      query: {
        'track_id': music.meta.songId.toString(),
        // This H5 endpoint requires web identity, even in the Android app.
        'device_platform': 'web',
      },
    );
    final lyric = data['lyric'];
    if (lyric is Map) return QsLyric.parse(lyric);
    if (data['track'] is Map) return const LyricInfo(lyric: '');
    throw Exception('汽水音乐歌词加载失败');
  }

  static List<MusicInfo> _rankedTracks(Object? resources) => [
    for (final resource in _maps(resources))
      if (parseTrack(
            _map(_map(_map(resource['entity'])['ranked_track'])['track']),
          )
          case final MusicInfo music)
        music,
  ];

  static MusicInfo? parseTrack(Map track) {
    final id = _text(track['id']);
    final name = _text(track['name']);
    if (id == null || name == null) return null;
    final album = _map(track['album']);
    return buildMusicInfo(
      name: name,
      singer: _maps(track['artists'])
          .map(
            (artist) => _text(artist['name'] ?? artist['simple_display_name']),
          )
          .whereType<String>()
          .join('、'),
      source: MusicSource.qs,
      songId: id,
      // Catalogue metadata does not establish playable qualities.
      qualitys: const [],
      interval: formatPlayTime((_int(track['duration']) ?? 0) / 1000),
      albumName: _text(album['name']) ?? '',
      albumId: _text(album['id']),
      picUrl: imageUrl(album['url_cover']),
    );
  }

  static String? imageUrl(Object? value) {
    if (value is String) return _text(value);
    final image = _map(value);
    final urls = image['urls'];
    if (urls is! List || urls.isEmpty) return null;
    final base = _text(urls.first);
    if (base == null) return null;
    final uri = _text(image['uri']);
    if (image['need_complete_url'] == true || uri == null) return base;
    final prefix = _text(image['template_prefix']);
    final template = prefix == null
        ? 'c5_640x640.jpg'
        : '$prefix-crop-center:640:640.jpg';
    return '$base$uri~$template';
  }

  static Map _map(Object? value) => value is Map ? value : const {};
  static Iterable<Map> _maps(Object? value) =>
      value is List ? value.whereType<Map>() : const <Map>[];
  static String? _text(Object? value) {
    final text = value?.toString().trim();
    return text == null || text.isEmpty ? null : text;
  }

  static int? _int(Object? value) =>
      value is num ? value.toInt() : int.tryParse(value?.toString() ?? '');
  static int _limit(int? value) =>
      value == null || value <= 0 ? 10000 : value.clamp(1, 10000);
}
